SAHIH_SUNAN=('abudawud','tirmidhi','nasai','ibnmajah')
def ok(b,h):
    if b in('bukhari','muslim'): return True
    for g in h.get('grades',[]):
        if 'Albani' in g.get('name',''):
            gr=g['grade'].strip().lower(); return gr.startswith('sahih') or gr.startswith('hasan')
    return False
cand=collections.defaultdict(list); seen=set()
for b in ('bukhari','muslim')+SAHIH_SUNAN:
    for h in book(b):
        if not ok(b,h) or h['num']<=0: continue
        for th,kws in T.items():
            hit=[k for k in kws if k in h['n']]
            if hit:
                key=(th,b,h['num'])
                if key in seen: continue
                seen.add(key)
                cand[th].append(dict(book=b,num=h['num'],kw=hit[0],len=len(h['n']),snip=h['n'][-260:]))
